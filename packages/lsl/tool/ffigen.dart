import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final root = Platform.script.resolve('../');
  await FfiGenerator(
    input: Input(
      entryPoints: [root.resolve('third_party/liblsl/include/lsl_c.h')],
    ),
    visitors: [
      Visitor(
        // The native library exposes the complete LSL C API for advanced use.
        func: (node) {
          node.isIncluded = node.originalName.startsWith('lsl_');
          node.recordUse = true;
        },
        enumClass: (node) {
          node.isIncluded = node.originalName.startsWith('lsl_');
          node.style = EnumStyle.intConstants;
          // LSL headers assert a four-byte enum size for the supported ABIs.
          node.silenceWarning = true;
        },
        macroConstant: (node) =>
            node.isIncluded = node.originalName.startsWith('LSL_'),
      ),
    ],
    output: Output(
      dart: DartOutput(path: root.resolve('lib/src/third_party/liblsl.g.dart')),
      recordUseMapping: root.resolve(
        'lib/src/third_party/liblsl.record_use_mapping.g.dart',
      ),
      commentType: CommentType.none(),
      preamble: '''// Copyright (C) 2012 Christian A. Kothe.
// LSL declarations use the MIT license in third_party/liblsl/LICENSE.
// Generated by package:ffigen. Do not edit manually.
// ignore_for_file: type=lint, unused_import, unused_element, unused_field, experimental_member_use
''',
    ),
  ).generate();
}
